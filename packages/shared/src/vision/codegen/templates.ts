import type { OpModeKind, OpModeStyle } from "../../opmode/types.js";
import { renderEasyOpenCvPipelineSource } from "../easyopencv/templates.js";
import type { VisionCodegenKind } from "./types.js";
import { VISION_CODEGEN_GENERATED_MARKER } from "./constants.js";

export interface VisionCodegenTemplateInput {
  packageName: string;
  className: string;
  displayName: string;
  opModeKind: OpModeKind;
  style: OpModeStyle;
  group?: string;
  cameraName: string;
  pipelineClassName?: string;
  limelightTableName?: string;
  useDashboardStream?: boolean;
  robotConfigName?: string;
}

function escapeJavaString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function opModeAnnotation(input: VisionCodegenTemplateInput): string {
  const type = input.opModeKind === "teleop" ? "TeleOp" : "Autonomous";
  const parts = [`name="${escapeJavaString(input.displayName)}"`];
  if (input.group?.trim()) {
    parts.push(`group="${escapeJavaString(input.group.trim())}"`);
  }
  return `@${type}(${parts.join(", ")})`;
}

function generatedHeader(kind: string): string {
  return `/**
 * ${VISION_CODEGEN_GENERATED_MARKER} — ${kind}.
 * Java TeamCode only. Review imports against your FTC SDK version before deploying.
 */`;
}

export function renderEasyOpenCvPipelineFile(input: VisionCodegenTemplateInput): string {
  const pipelineClass = input.pipelineClassName ?? `${input.className}Pipeline`;
  return renderEasyOpenCvPipelineSource({
    packageName: input.packageName,
    className: pipelineClass,
  }).replace(
    "EasyOpenCV pipeline stub generated by FTC Dev Tools (VISION-09).",
    `${VISION_CODEGEN_GENERATED_MARKER} — EasyOpenCV pipeline.`,
  );
}

export function renderEasyOpenCvOpModeSource(input: VisionCodegenTemplateInput): string {
  const pipelineClass = input.pipelineClassName ?? `${input.className}Pipeline`;
  const annotation = opModeAnnotation(input);
  const configHint = input.robotConfigName ? `Robot config: ${input.robotConfigName}. ` : "";
  const dashboardImport = input.useDashboardStream
    ? "import com.acmerobotics.dashboard.FtcDashboard;\n"
    : "";
  const dashboardField = input.useDashboardStream ? "\n    private FtcDashboard dashboard;" : "";
  const dashboardInit = input.useDashboardStream
    ? "\n        dashboard = FtcDashboard.getInstance();"
    : "";
  const dashboardStream = input.useDashboardStream
    ? "\n            dashboard.startCameraStream(webcam);"
    : "";
  const dashboardStop = input.useDashboardStream
    ? "\n            dashboard.stopCameraStream(webcam);"
    : "";

  return `package ${input.packageName};

import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.eventloop.opmode.${input.opModeKind === "teleop" ? "TeleOp" : "Autonomous"};
import com.qualcomm.robotcore.hardware.WebcamName;
import org.openftc.easyopencv.OpenCvWebcam;
import org.openftc.easyopencv.OpenCvWebcamFactory;
${dashboardImport}
${generatedHeader("EasyOpenCV OpMode")}

${annotation}
public class ${input.className} extends LinearOpMode {
    private OpenCvWebcam webcam;${dashboardField}

    @Override
    public void runOpMode() {
        // ${configHint}Camera: "${input.cameraName}"
        ${pipelineClass} pipeline = new ${pipelineClass}();
        webcam = OpenCvWebcamFactory.getInstance()
                .createWebcam(hardwareMap.get(WebcamName.class, "${input.cameraName}"), pipeline);${dashboardInit}

        webcam.openCameraDeviceAsync();
        while (!isStopRequested() && !webcam.isOpen()) {
            idle();
        }

        telemetry.addData("Camera", "${input.cameraName}");
        telemetry.update();
        waitForStart();

        try {${dashboardStream}
            while (opModeIsActive()) {
                telemetry.addData("FPS", webcam.getFrameProcessingTimeMs());
                telemetry.update();
            }
        } finally {
            if (webcam != null) {
                webcam.closeCameraDevice();${dashboardStop}
            }
        }
    }
}
`;
}


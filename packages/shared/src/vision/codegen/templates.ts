export function renderLimelightOpModeSource(input: VisionCodegenTemplateInput): string {
  const tableName = input.limelightTableName ?? "limelight";
  const annotation = opModeAnnotation({
    ...input,
    opModeKind: "teleop",
    displayName: input.displayName,
  });

  return `package ${input.packageName};

import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import edu.wpi.first.networktables.NetworkTable;
import edu.wpi.first.networktables.NetworkTableInstance;

${generatedHeader("Limelight NetworkTables integration")}

${annotation}
public class ${input.className} extends LinearOpMode {
    private NetworkTable limelight;
    private int activePipeline = 0;

    @Override
    public void runOpMode() {
        // --- ${VISION_CODEGEN_GENERATED_MARKER}: Limelight init ---
        NetworkTableInstance inst = NetworkTableInstance.getDefault();
        limelight = inst.getTable("${tableName}");
        limelight.getEntry("pipeline").setNumber(activePipeline);

        telemetry.addLine("Limelight table: ${tableName}");
        telemetry.addLine("D-pad up/down: switch pipeline index");
        telemetry.update();
        waitForStart();

        while (opModeIsActive()) {
            handlePipelineSwitch();
            readLimelightResults();
            telemetry.update();
        }
    }

    private void handlePipelineSwitch() {
        if (gamepad1.dpad_up) {
            activePipeline = Math.max(0, activePipeline - 1);
            limelight.getEntry("pipeline").setNumber(activePipeline);
        } else if (gamepad1.dpad_down) {
            activePipeline = activePipeline + 1;
            limelight.getEntry("pipeline").setNumber(activePipeline);
        }
        telemetry.addData("Pipeline", activePipeline);
    }

    private void readLimelightResults() {
        // --- ${VISION_CODEGEN_GENERATED_MARKER}: Limelight result loop ---
        double tv = limelight.getEntry("tv").getDouble(0.0);
        boolean targetValid = tv == 1.0;
        double tx = limelight.getEntry("tx").getDouble(0.0);
        double ty = limelight.getEntry("ty").getDouble(0.0);
        double ta = limelight.getEntry("ta").getDouble(0.0);

        telemetry.addData("Target valid", targetValid);
        telemetry.addData("tx", tx);
        telemetry.addData("ty", ty);
        telemetry.addData("ta", ta);
    }
}
`;
}

export function renderDashboardStreamOpModeSource(input: VisionCodegenTemplateInput): string {
  const annotation = opModeAnnotation({
    ...input,
    opModeKind: "teleop",
    displayName: input.displayName,
  });
  const configHint = input.robotConfigName ? `Robot config: ${input.robotConfigName}. ` : "";

  return `package ${input.packageName};

import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import com.qualcomm.robotcore.hardware.WebcamName;
import com.acmerobotics.dashboard.FtcDashboard;
import org.firstinspires.ftc.vision.VisionPortal;

${generatedHeader("FTC Dashboard camera stream")}

${annotation}
public class ${input.className} extends LinearOpMode {
    private VisionPortal visionPortal;
    private FtcDashboard dashboard;

    @Override
    public void runOpMode() {
        // ${configHint}Camera: "${input.cameraName}"
        dashboard = FtcDashboard.getInstance();
        visionPortal = new VisionPortal.Builder()
                .setCamera(hardwareMap.get(WebcamName.class, "${input.cameraName}"))
                .build();
        dashboard.startCameraStream(visionPortal);

        telemetry.addLine("Dashboard camera stream active.");
        telemetry.update();
        waitForStart();

        try {
            while (opModeIsActive()) {
                idle();
            }
        } finally {
            if (dashboard != null && visionPortal != null) {
                dashboard.stopCameraStream(visionPortal);
            }
            closeVisionPortal();
        }
    }

    private void closeVisionPortal() {
        if (visionPortal != null) {
            visionPortal.close();
            visionPortal = null;
        }
    }
}
`;
}

export function renderVisionCodegenSource(
  kind: VisionCodegenKind,
  input: VisionCodegenTemplateInput,
): { files: Array<{ relativePath: string; content: string }> } {
  const javaRoot = input.packageName.split(".").join("/");
  const basePath = `TeamCode/src/main/java/${javaRoot}`;

  switch (kind) {
    case "easyopencv": {
      const pipelineClass = input.pipelineClassName ?? `${input.className}Pipeline`;
      return {
        files: [
          {
            relativePath: `${basePath}/${pipelineClass}.java`.replace(/\\/g, "/"),
            content: renderEasyOpenCvPipelineFile(input),
          },
          {
            relativePath: `${basePath}/${input.className}.java`.replace(/\\/g, "/"),
            content: renderEasyOpenCvOpModeSource(input),
          },
        ],
      };
    }
    case "visionportal-apriltag":
      return {
        files: [
          {
            relativePath: `${basePath}/${input.className}.java`.replace(/\\/g, "/"),
            content: renderVisionPortalAprilTagOpModeSource(input),
          },
        ],
      };
    case "visionportal-color":
      return {
        files: [
          {
            relativePath: `${basePath}/${input.className}.java`.replace(/\\/g, "/"),
            content: renderVisionPortalColorOpModeSource(input),
          },
        ],
      };
    case "limelight":
      return {
        files: [
          {
            relativePath: `${basePath}/${input.className}.java`.replace(/\\/g, "/"),
            content: renderLimelightOpModeSource(input),
          },
        ],
      };
    case "dashboard-stream":
      return {
        files: [
          {
            relativePath: `${basePath}/${input.className}.java`.replace(/\\/g, "/"),
            content: renderDashboardStreamOpModeSource(input),
          },
        ],
      };
    default:
      return { files: [] };
  }
}
